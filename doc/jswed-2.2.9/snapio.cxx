int TapeHeader::read(FILE *fp)
{
	jswByte dlen[2];  
	int datalen;
	char maybe_hdr[19];
	
	if (fread(dlen, 1, 2, fp) < 2) 
	{
		return ZXE_CANCEL;	// End of .TAP file
	}
	datalen = (dlen[0] & 0xFF) + 256 * (dlen[1] & 0xFF);
	if (datalen != 0x13)
	{
		fseek(fp, datalen, SEEK_CUR);
		return ZXE_CONTINUE;
	}
	if (fread(maybe_hdr, 1, 19, fp) < 19)
		return retError("R TAP loading error");
	if (maybe_hdr[0] != 0) return ZXE_CONTINUE;	
	if (maybe_hdr[1] >  3) return ZXE_CONTINUE;
	memcpy(m_data, maybe_hdr + 1, 17);
	return ZXE_OK;
}

int TapeHeader::readData(FILE *fp, jswByte *buf)
{
        jswByte dlen[2];
        int datalen, ch;

        if (fread(dlen, 1, 2, fp) < 2)
		return retError("R TAP loading error");
        datalen = (dlen[0] & 0xFF) + 256 * (dlen[1] & 0xFF);
	if (datalen - 2 != getSize())
	{
		return retError("R TAP loading error");
	}	
	ch = fgetc(fp);	// Block type
	if (ch != 0xFF)
	{
		ungetc(ch, fp);
        	return retError("R TAP loading error");
	}
	if (fread(buf, 1, datalen-2, fp) < (unsigned int)datalen-2)
	{
		return retError("R TAP loading error");
	}
	fgetc(fp);	// Checksum, ignored	
	return ZXE_OK;
}


