static int tapWrite(FILE *fp, char *name, const jswByte *header, 
			const jswByte *data)
{
	jswByte tapHeader[25];
	jswByte csum;
	unsigned n, len;

	memset(tapHeader, 0, sizeof(tapHeader));	
	tapHeader[0] = 0x13;
	tapHeader[3] = header[15];
	memcpy(tapHeader + 4,  name, 10);
	memcpy(tapHeader + 14, header + 16, 6);
	
	csum = 0;
	for (n = 2; n < 20; n++) csum ^= tapHeader[n];
	tapHeader[n] = csum;
	if (fwrite(tapHeader, 1, 21, fp) < 21) return 0;
	
	len = header[16] + 256 * header[17];
	csum = 0xFF;
	for (n = 0; n < len; n++) csum ^= data[n];
	
	tapHeader[0] = ((len + 2)     ) & 0xFF;
	tapHeader[1] = ((len + 2) >> 8) & 0xFF;
	tapHeader[2] = 0xFF;
	if (fwrite(tapHeader, 1, 3, fp) < 3) return 0;
	if (fwrite(data,      1, len, fp) < len) return 0;
	if (fwrite(&csum,     1, 1, fp) < 1) return 0;
	return 1;
}

static void constructHeader(jswByte *header, int type, int len, int addr)
{
        jswByte csum;
        int n;

        memcpy(header, hiload_head, 128);
        header[11] = ((len + 128)      ) & 0xFF;
        header[12] = ((len + 128) >>  8) & 0xFF;
        header[13] = ((len + 128) >> 16) & 0xFF;
        header[14] = ((len + 128) >> 24) & 0xFF;
        header[15] = type;
        header[16] = len & 0xFF;
        header[17] = (len >> 8) & 0xFF;
	header[18] = addr & 0xFF;
	header[19] = (addr >> 8) & 0xFF;

	csum = 0;	
	for (n = 0; n < 127; n++) csum += header[n];
	header[n] = csum;
}

static int tapWrite(FILE *fp, char *name, int len, int addr, 
			const jswByte *data)
{
	jswByte header[128];
	
	constructHeader(header, 3, len, addr);

	return tapWrite(fp, name, header, data);
}

